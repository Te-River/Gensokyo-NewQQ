// ExtractQQErrorCode 从 err.Error() 中提取 QQ API 错误码
//
// 匹配模式："code":12345 或 "code":12345,
// 返回 0 表示未找到错误码。
//
// 示例输入：`PostGroupMessage failed: {"code":22009,"message":"频控"}`
// 返回：22009
func ExtractQQErrorCode(errMsg string) int {
	if errMsg == "" {
		return 0
	}
	m := qqErrorCodeRe.FindStringSubmatch(errMsg)
	if len(m) < 2 {
		return 0
	}
	code, err := strconv.Atoi(m[1])
	if err != nil {
		return 0
	}
	return code
}

// FormatQQError 将错误格式化为开发者可读的提示
//
// 输出格式：
//   已识别：[QQ API 错误码 xxxxx] 描述。排查建议：xxx
//   未识别：[QQ API 错误码 xxxxx] 未识别错误码，请查阅官方文档
//   无错误码：[QQ API] 未检测到错误码，原始错误：xxx
//
// 用法：
//   if err != nil {
//       mylog.Printf("发送失败: %v", err)
//       mylog.Printf("%s", FormatQQError(err))  // 追加这一行
//   }
func FormatQQError(err error) string {
	if err == nil {
		return ""
	}
	errMsg := err.Error()
	code := ExtractQQErrorCode(errMsg)
	if code == 0 {
		return "[QQ API] 未检测到错误码，原始错误：" + errMsg
	}
	ec, ok := qqErrorCodes[code]
	if !ok {
		return "[QQ API 错误码 " + strconv.Itoa(code) + "] 未识别错误码，请查阅官方文档：https://bot.q.qq.com/wiki/develop/api-v2/dev-prepare/api-call-guide.html#openapi-错误码"
	}
	return "[QQ API 错误码 " + strconv.Itoa(code) + "] " + ec.Description + "。排查建议：" + ec.Suggestion
}
